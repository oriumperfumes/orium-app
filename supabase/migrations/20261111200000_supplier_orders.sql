-- Pedidos feitos aos fornecedores (registro permanente) e conferência na chegada.
create table if not exists public.supplier_orders (
  id uuid primary key default gen_random_uuid(),
  seq integer generated by default as identity,
  supplier_id uuid references public.suppliers(id) on delete set null,
  supplier_name text not null default '',
  status text not null default 'enviado' check (status in ('enviado','conferido','com_problema','cancelado')),
  units integer not null default 0,
  total numeric(12,2) not null default 0,
  message text,
  sent_via text not null default 'whatsapp' check (sent_via in ('whatsapp','manual')),
  created_by uuid,
  created_at timestamptz not null default now(),
  checked_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.supplier_order_items (
  id uuid primary key default gen_random_uuid(),
  supplier_order_id uuid not null references public.supplier_orders(id) on delete cascade,
  restock_item_id uuid references public.restock_items(id) on delete set null,
  product_id uuid,
  name text not null default 'Produto',
  brand text,
  image_url text,
  volume_ml integer,
  quantity integer not null default 1,
  unit_cost numeric(12,2) not null default 0,
  result text check (result in ('ok','faltou','quebrado','errado')),
  received_qty integer,
  issue_qty integer not null default 0,
  issue_note text,
  resolution text check (resolution in ('chegou','repedido','reembolso','credito')),
  resolved_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists supplier_order_items_order_idx on public.supplier_order_items(supplier_order_id);
create index if not exists supplier_order_items_restock_idx on public.supplier_order_items(restock_item_id);
create index if not exists supplier_orders_created_idx on public.supplier_orders(created_at desc);
alter table public.supplier_orders enable row level security;
alter table public.supplier_order_items enable row level security;
drop policy if exists "staff supplier orders" on public.supplier_orders;
create policy "staff supplier orders" on public.supplier_orders for all using (is_staff(auth.uid())) with check (is_staff(auth.uid()));
drop policy if exists "staff supplier order items" on public.supplier_order_items;
create policy "staff supplier order items" on public.supplier_order_items for all using (is_staff(auth.uid())) with check (is_staff(auth.uid()));
